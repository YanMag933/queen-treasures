function hashString(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function dayKey(date = new Date()) {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

function pickFrom(list, seed) {
  const pool = list && list.length ? list : COACH_DAILY;
  return pool[hashString(String(seed)) % pool.length];
}

function buildCoach(ctx) {
  const key = dayKey(ctx.now);
  const daily = pickFrom(COACH_DAILY, `${key}|daily`);
  let extra = null;
  let tone = "daily";

  if (ctx.loggedToday && ctx.incomeProgress >= 0.9 && ctx.expenseProgress <= 1) {
    extra = pickFrom(COACH_PRAISE, `${key}|glow`);
    tone = "praise";
  } else if (ctx.loggedToday) {
    extra = pickFrom(COACH_PRAISE, `${key}|logged`);
    tone = "praise";
  } else if (ctx.expenseProgress > 1) {
    extra = pickFrom(COACH_NUDGE.filter((x) => x.title.includes("Расходы") || x.title.includes("подсветим")), `${key}|over`);
    tone = "nudge";
  } else if (ctx.daysWithoutLog >= 1) {
    extra = COACH_NUDGE.find((x) => x.title.includes("молчит")) || pickFrom(COACH_NUDGE, `${key}|silence`);
    tone = "nudge";
  } else if (ctx.incomeProgress < 0.55 && ctx.dayOfMonth >= 12) {
    extra = pickFrom(COACH_NUDGE.filter((x) => x.title.includes("Доход") || x.title.includes("Зал")), `${key}|income`);
    tone = "nudge";
  } else if (ctx.extraOver) {
    extra = COACH_NUDGE.find((x) => x.title.includes("Дополнительно")) || pickFrom(COACH_NUDGE, `${key}|extra`);
    tone = "nudge";
  } else if (ctx.debtPaidMonth <= 0 && ctx.dayOfMonth >= 8 && ctx.monthPlan.debts > 0) {
    extra = COACH_NUDGE.find((x) => x.title.includes("Минимумы")) || pickFrom(COACH_NUDGE, `${key}|min`);
    tone = "nudge";
  }

  const message = extra && extra.title !== daily.title ? extra : daily;
  const footnote = extra && extra !== message ? daily.body : "Надпись обновляется каждый день и подстраивается под твои записи.";
  return { ...message, footnote, tone, dayKey: key };
}
